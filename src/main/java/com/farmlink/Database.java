package com.farmlink;
import java.sql.*;
import java.nio.file.*;
import java.util.*;
/** JDBC database adapter: embedded HSQLDB by default, or external MySQL via environment variables. */
public final class Database {
    private final String jdbcUrl;
    private final String dbUser;
    private final String dbPassword;
    private final boolean mysql;

    public Database(Path dataDir) throws Exception {
        String mode = System.getenv().getOrDefault("FARMLINK_DB", "hsqldb").trim();
        mysql = "mysql".equalsIgnoreCase(mode);
        if (mysql) {
            jdbcUrl = System.getenv().getOrDefault("FARMLINK_MYSQL_URL", "jdbc:mysql://localhost:3306/farmlink_db");
            dbUser = System.getenv().getOrDefault("FARMLINK_DB_USER", "farmlink_app");
            dbPassword = System.getenv("FARMLINK_DB_PASSWORD");
            if (dbPassword == null || dbPassword.isBlank()) {
                throw new IllegalStateException("MySQL password is missing. Set FARMLINK_DB_PASSWORD before starting run.bat.");
            }
            try {
                Class.forName("com.mysql.cj.jdbc.Driver");
            } catch (ClassNotFoundException e) {
                throw new IllegalStateException("MySQL Connector/J .jar is missing. Download it from dev.mysql.com/downloads/connector/j/ and put the .jar in FarmLink/lib/.", e);
            }
            // CREATE TABLE is intentionally not required for the application user.
            // First import database/mysql_schema.sql as a MySQL administrator.
            try (Connection c = connect(); Statement st = c.createStatement()) {
                for (String table : List.of("users", "harvests", "inquiries", "messages", "saved", "sessions")) {
                    try (ResultSet ignored = st.executeQuery("SELECT 1 FROM " + table + " LIMIT 0")) {
                        // This also validates that the app account has SELECT permission.
                    }
                }
            } catch (SQLException ex) {
                throw new SQLException("Cannot connect to FarmLink MySQL tables. Confirm MySQL is running, credentials are correct, and database/mysql_schema.sql was imported to farmlink_db. Cause: " + ex.getMessage(), ex);
            }
            System.out.println("Database: MySQL (" + jdbcUrl + ")");
        } else if ("hsqldb".equalsIgnoreCase(mode)) {
            Files.createDirectories(dataDir.toAbsolutePath());
            jdbcUrl = "jdbc:hsqldb:file:" + dataDir.toAbsolutePath().resolve("farmlink").toString().replace('\\', '/');
            dbUser = "sa";
            dbPassword = "";
            Class.forName("org.hsqldb.jdbcDriver");
            migrate();
            System.out.println("Database: embedded HSQLDB (" + dataDir.toAbsolutePath() + ")");
        } else {
            throw new IllegalArgumentException("FARMLINK_DB must be hsqldb or mysql; got: " + mode);
        }
    }

    public Connection connect() throws SQLException {
        return DriverManager.getConnection(jdbcUrl, dbUser, dbPassword);
    }
    private void migrate() throws SQLException {
        try(Connection c=connect();Statement s=c.createStatement()){
            if(!exists(c,"USERS"))s.execute("CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role VARCHAR(12) NOT NULL, first_name VARCHAR(90) NOT NULL, last_name VARCHAR(90) NOT NULL, nic VARCHAR(40) NOT NULL, email VARCHAR(150), phone VARCHAR(30) NOT NULL, district VARCHAR(80) NOT NULL, province VARCHAR(80) NOT NULL, address VARCHAR(255) NOT NULL, password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE(nic))");
            if(!exists(c,"HARVESTS"))s.execute("CREATE TABLE harvests (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, farmer_id INTEGER NOT NULL, title VARCHAR(100) NOT NULL, category VARCHAR(60) NOT NULL, district VARCHAR(80) NOT NULL, price DOUBLE NOT NULL, quantity DOUBLE NOT NULL, unit VARCHAR(30) NOT NULL, status VARCHAR(15) NOT NULL, description VARCHAR(3000) NOT NULL, image LONGVARCHAR, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(farmer_id) REFERENCES users(id))");
            if(!exists(c,"INQUIRIES"))s.execute("CREATE TABLE inquiries (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, harvest_id INTEGER NOT NULL, buyer_id INTEGER NOT NULL, farmer_id INTEGER NOT NULL, quantity DOUBLE NOT NULL, status VARCHAR(15) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(harvest_id) REFERENCES harvests(id), FOREIGN KEY(buyer_id) REFERENCES users(id), FOREIGN KEY(farmer_id) REFERENCES users(id))");
            if(!exists(c,"MESSAGES"))s.execute("CREATE TABLE messages (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, inquiry_id INTEGER NOT NULL, sender_id INTEGER NOT NULL, body VARCHAR(2000) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(inquiry_id) REFERENCES inquiries(id), FOREIGN KEY(sender_id) REFERENCES users(id))");
            if(!exists(c,"SAVED"))s.execute("CREATE TABLE saved (buyer_id INTEGER NOT NULL, harvest_id INTEGER NOT NULL, PRIMARY KEY (buyer_id,harvest_id), FOREIGN KEY(buyer_id) REFERENCES users(id), FOREIGN KEY(harvest_id) REFERENCES harvests(id))");
            if(!exists(c,"SESSIONS"))s.execute("CREATE TABLE sessions (token_hash VARCHAR(100) PRIMARY KEY, user_id INTEGER NOT NULL, expires_at TIMESTAMP NOT NULL, FOREIGN KEY(user_id) REFERENCES users(id))");
        }
    }
    private boolean exists(Connection c,String name) throws SQLException{try(ResultSet r=c.getMetaData().getTables(null,null,name,new String[]{"TABLE"})){return r.next();}}
    public static int id(Connection c) throws SQLException {
        String vendor = c.getMetaData().getDatabaseProductName().toLowerCase(Locale.ROOT);
        String query = vendor.contains("mysql") ? "SELECT LAST_INSERT_ID()" : "CALL IDENTITY()";
        try (Statement s = c.createStatement(); ResultSet r = s.executeQuery(query)) {
            if (!r.next()) throw new SQLException("Unable to retrieve new record ID");
            return r.getInt(1);
        }
    }
    public static void bind(PreparedStatement p,Object... values)throws SQLException{
        for(int i=0;i<values.length;i++){
            Object o=values[i]; if(o==null)p.setNull(i+1,Types.VARCHAR); else if(o instanceof Integer v)p.setInt(i+1,v);
            else if(o instanceof Double v)p.setDouble(i+1,v);else if(o instanceof java.sql.Timestamp v)p.setTimestamp(i+1,v);else p.setString(i+1,String.valueOf(o));
        }
    }
    public void shutdown() {
        if (mysql) return; // MySQL is an independent server; never shut it down.
        try (Connection c = connect(); Statement s = c.createStatement()) {
            s.execute("SHUTDOWN");
        } catch (Exception e) {
            System.err.println("Database shutdown: " + e.getMessage());
        }
    }
}

-- FarmLink embedded HSQLDB 1.8 schema (reference only).
-- The application creates these tables automatically in Database.java.
-- For a fresh database only; do not run twice against existing tables.

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role VARCHAR(12) NOT NULL,
  first_name VARCHAR(90) NOT NULL,
  last_name VARCHAR(90) NOT NULL,
  nic VARCHAR(40) NOT NULL,
  email VARCHAR(150),
  phone VARCHAR(30) NOT NULL,
  district VARCHAR(80) NOT NULL,
  province VARCHAR(80) NOT NULL,
  address VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(nic)
);

CREATE TABLE harvests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmer_id INTEGER NOT NULL,
  title VARCHAR(100) NOT NULL,
  category VARCHAR(60) NOT NULL,
  district VARCHAR(80) NOT NULL,
  price DOUBLE NOT NULL,
  quantity DOUBLE NOT NULL,
  unit VARCHAR(30) NOT NULL,
  status VARCHAR(15) NOT NULL,
  description VARCHAR(3000) NOT NULL,
  image LONGVARCHAR,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(farmer_id) REFERENCES users(id)
);

CREATE TABLE inquiries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  harvest_id INTEGER NOT NULL,
  buyer_id INTEGER NOT NULL,
  farmer_id INTEGER NOT NULL,
  quantity DOUBLE NOT NULL,
  status VARCHAR(15) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(harvest_id) REFERENCES harvests(id),
  FOREIGN KEY(buyer_id) REFERENCES users(id),
  FOREIGN KEY(farmer_id) REFERENCES users(id)
);

CREATE TABLE messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inquiry_id INTEGER NOT NULL,
  sender_id INTEGER NOT NULL,
  body VARCHAR(2000) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(inquiry_id) REFERENCES inquiries(id),
  FOREIGN KEY(sender_id) REFERENCES users(id)
);

CREATE TABLE saved (
  buyer_id INTEGER NOT NULL,
  harvest_id INTEGER NOT NULL,
  PRIMARY KEY (buyer_id,harvest_id),
  FOREIGN KEY(buyer_id) REFERENCES users(id),
  FOREIGN KEY(harvest_id) REFERENCES harvests(id)
);

CREATE TABLE sessions (
  token_hash VARCHAR(100) PRIMARY KEY,
  user_id INTEGER NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  FOREIGN KEY(user_id) REFERENCES users(id)
);
